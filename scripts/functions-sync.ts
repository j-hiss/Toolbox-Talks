// Copies what the server functions need from the app into supabase/functions/_shared/, so each deploys on its own:
// - tailor-talk: the library and the AI rules (it looks the library talk up itself, never trusting a caller's text).
// - weekly-digest: src/lib/digest.ts bundled with the app's own query functions and report math (digest.js), so the
//   email is built by exactly the code the app's preview uses.
//   npm run functions:sync          (scripts/functions-sync.test.ts fails if the copies are out of date)
import { readFileSync, writeFileSync } from "node:fs";
import { buildSync } from "esbuild";
import { join } from "node:path";
import { TALKS } from "../src/content/talks";
import { INDUSTRIES } from "../src/core/industries";
import { WORK_SETTINGS } from "../src/core/worksetting";

const root = join(import.meta.dirname, "..");
export const SHARED = join(root, "supabase", "functions", "_shared");

export function libraryJson(): string {
  return JSON.stringify({
    talks: Object.fromEntries(TALKS.map((t) => [t.id, { talk: t.content.en, sources: t.sources.map((s) => s.label) }])),
    industries: Object.fromEntries(INDUSTRIES.map((i) => [i.id, `${i.name}: ${i.sub}`])),
    workSettings: Object.fromEntries(WORK_SETTINGS.map((w) => [w.id, w.name])),
  });
}

export const aiTailorCopy = () =>
  "// GENERATED by scripts/functions-sync.ts from src/core/aiTailor.ts. Do not edit; run npm run functions:sync.\n" +
  readFileSync(join(root, "src", "core", "aiTailor.ts"), "utf8");

/** The weekly-digest bundle. Supabase's client comes from Deno's npm import at run time, never bundled. */
export function digestBundle(): string {
  const out = buildSync({
    entryPoints: [join(root, "src", "lib", "digest.ts")], bundle: true, format: "esm", platform: "neutral", target: "es2022", write: false,
    alias: { "@": join(root, "src") }, external: ["@supabase/supabase-js"], legalComments: "none", charset: "utf8",
  });
  const text = out.outputFiles[0].text.replaceAll('"@supabase/supabase-js"', '"npm:@supabase/supabase-js@2.45.4"');
  return "// GENERATED by scripts/functions-sync.ts from src/lib/digest.ts. Do not edit; run npm run functions:sync.\n" + text;
}

if (process.argv[1]?.endsWith("functions-sync.ts")) {
  writeFileSync(join(SHARED, "library.json"), libraryJson());
  writeFileSync(join(SHARED, "aiTailor.ts"), aiTailorCopy());
  writeFileSync(join(SHARED, "digest.js"), digestBundle());
  console.log("Updated supabase/functions/_shared/library.json, aiTailor.ts and digest.js");
}
